def _match_signatures(headers_text: str, body: str, cookie_str: str, status_code: int) -> list[dict]:
    """Matches response content against the signature lists."""
    detections = []
    for waf_name, sigs in WAF_SIGNATURES.items():
        evidence = []
        for pattern in sigs.get("headers", []):
            try:
                match = re.search(pattern, headers_text)
                if match:
                    evidence.append(f"Header match: {match.group(0)[:80]}")
            except re.error:
                continue
        for pattern in sigs.get("body", []):
            try:
                match = re.search(pattern, body[:60000])
                if match:
                    evidence.append(f"Body match: {match.group(0)[:80]}")
            except re.error:
                continue
        for pattern in sigs.get("cookies", []):
            try:
                match = re.search(pattern, cookie_str)
                if match:
                    evidence.append(f"Cookie match: {match.group(0)[:60]}")
            except re.error:
                continue
        if status_code in sigs.get("codes", []):
            evidence.append(f"Status code {status_code} is a known WAF block indicator")
        if evidence:
            detections.append({"waf_name": waf_name, "evidence": evidence, "evidence_count": len(evidence)})
    detections.sort(key=lambda x: x["evidence_count"], reverse=True)
    return detections


async def _probe(session: aiohttp.ClientSession, url: str, extra_params: str = "", extra_headers: dict = None) -> dict | None:
    """Sends a single probe request and returns response body, cookies, and status code."""
    full_url = f"{url}{extra_params}" if extra_params else url
    headers = {
        "User-Agent": "Mozilla/5.0 (Windows NT 10.0; Win64; x64) AppleWebKit/537.36",
        "Accept": "text/html,application/xhtml+xml,application/xml;q=0.9,*/*;q=0.8",
    }
    if extra_headers:
        headers.update(extra_headers)
    try:
        async with session.get(full_url, ssl=False, allow_redirects=True, headers=headers) as resp:
            body = await resp.text(errors="ignore")
            headers_text = "\n".join(f"{k}: {v}" for k, v in resp.headers.items())
            cookie_str = "; ".join(f"{c.key}={c.value}" for c in resp.cookies.values())
            return {
                "status_code": resp.status,
                "headers_text": headers_text,
                "body": body[:60000],
                "url": str(resp.url),
                "cookie_str": cookie_str,
            }
    except (asyncio.TimeoutError, aiohttp.ClientConnectorError, ssl_mod.SSLError):
        return None
    except Exception:
        return None


async def detect(target: str) -> dict[str, Any]:
    """
    Main Entry Point: executes baseline + attack probes, matches signatures,
    and returns a summary of the WAF presence.
    """
    target_clean = target.replace("https://", "").replace("http://", "").split("/")[0]
    targets_to_try = [target_clean]
    if not target_clean.startswith("www."):
        targets_to_try.append(f"www.{target_clean}")
    timeout = aiohttp.ClientTimeout(total=TIMEOUTS.get("waf_detect", 60))

    probes = [
        {"name": "baseline",    "params": "",                                      "extra_headers": None},
        {"name": "xss_probe",   "params": "?q=<script>alert('xss')</script>",     "extra_headers": None},
        {"name": "sqli_probe",  "params": "?id=1'+OR+'1'='1",                     "extra_headers": None},
        {"name": "traversal",   "params": "?file=../../../../etc/passwd",          "extra_headers": None},
        {"name": "rce_probe",   "params": "?cmd=;ls",                             "extra_headers": None},
        {"name": "scanner_ua",  "params": "",                                      "extra_headers": {"User-Agent": "sqlmap/1.0"}},
        {"name": "bad_method",  "params": "?debug=true&test=<img src=x>",         "extra_headers": None},
    ]

    try:
        async with aiohttp.ClientSession(timeout=timeout) as session:
            all_detections = []
            probe_results = []

            for t_host in targets_to_try:
                for proto in ["https", "http"]:
                    base_url = f"{proto}://{t_host}"
                    probe_session_timeout = aiohttp.ClientTimeout(total=12.0, connect=5, sock_read=10)
                    probe_connector = aiohttp.TCPConnector(limit=35, limit_per_host=5)
                    async with aiohttp.ClientSession(connector=probe_connector, timeout=probe_session_timeout) as probe_session:
                        probe_tasks = [
                            _probe(probe_session, base_url, p["params"], p["extra_headers"])
                            for p in probes
                        ]
                        raw_results = await asyncio.gather(*probe_tasks, return_exceptions=True)

                    for probe, result in zip(probes, raw_results):
                        if not isinstance(result, dict):
                            continue
                        probe_detections = _match_signatures(
                            result["headers_text"], result["body"],
                            result["cookie_str"], result["status_code"],
                        )
                        probe_summary = {
                            "probe": probe["name"],
                            "url": result["url"],
                            "status_code": result["status_code"],
                            "waf_signals": len(probe_detections),
                        }
                        if probe["name"] != "baseline" and result["status_code"] in [403, 406, 419, 429, 501, 503]:
                            probe_summary["likely_blocked"] = True
                        probe_results.append(probe_summary)
                        all_detections.extend(probe_detections)

                    if probe_results:
                        break
                if probe_results:
                    break

            if not probe_results:
                return {
                    "status": "ok",
                    "waf_detected": False,
                    "waf_name": None,
                    "confidence": "none",
                    "all_detected": [],
                    "detections": [],
                    "probes": [],
                    "probes_blocked": 0,
                    "total_probes": 0,
                    "note": "Web service ports (80/443) did not respond or connections were filtered by network firewall.",
                }

            seen = {}
            for det in all_detections:
                name = det["waf_name"]
                if name not in seen or det["evidence_count"] > seen[name]["evidence_count"]:
                    seen[name] = det

            unique_detections = sorted(seen.values(), key=lambda x: x["evidence_count"], reverse=True)
            waf_detected = len(unique_detections) > 0
            primary_waf = unique_detections[0]["waf_name"] if unique_detections else None

            if unique_detections:
                max_evidence = unique_detections[0]["evidence_count"]
                confidence = "high" if max_evidence >= 3 else "medium" if max_evidence >= 2 else "low"
            else:
                confidence = "none"

            blocked_count = sum(1 for p in probe_results if p.get("likely_blocked"))

            return {
                "status": "ok",
                "waf_detected": waf_detected,
                "waf_name": primary_waf,
                "confidence": confidence,
                "all_detected": [d["waf_name"] for d in unique_detections],
                "detections": unique_detections,
                "probes": probe_results,
                "probes_blocked": blocked_count,
                "total_probes": len(probe_results),
            }

    except asyncio.TimeoutError:
        return {
            "status": "ok",
            "waf_detected": False,
            "waf_name": None,
            "confidence": "none",
            "all_detected": [],
            "detections": [],
            "probes": [],
            "probes_blocked": 0,
            "total_probes": 0,
            "note": f"WAF detection timed out after {TIMEOUTS.get('waf_detect', 45)}s.",
        }
    except Exception as e:
        return {
            "status": "ok",
            "waf_detected": False,
            "waf_name": None,
            "confidence": "none",
            "all_detected": [],
            "detections": [],
            "probes": [],
            "probes_blocked": 0,
            "total_probes": 0,
            "note": f"WAF detection notice: {str(e)[:120]}",
        }
